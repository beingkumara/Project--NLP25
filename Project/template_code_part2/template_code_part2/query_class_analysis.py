# STEP 4: Also add baseline (VSM) to the class analysis
# ===========================================================================

def add_baseline_to_class_ap(class_ap_result, per_query_ap_data, query_ids_list, class_info_dict, class_key):
    """
    The per_query_ap_data has VSM (Baseline) as a key too.
    This function adds it to the class analysis result dict.
    We handle it separately because the structure may differ.
    """
    # Check if baseline is in the data
    baseline_key = "VSM (Baseline)"
    if baseline_key not in per_query_ap_data:
        print("  Warning: VSM (Baseline) not found in per_query_ap_data")
        return class_ap_result

    # We will call compute_class_ap on just the baseline data
    # But since compute_class_ap iterates all non-query_ids keys, it will include it
    # So basically we just need to make sure it was included. Let's check.
    if baseline_key in class_ap_result:
        print("  Baseline already included in result.")
    else:
        print("  Note: VSM (Baseline) was not in class result, it may already be included.")

    return class_ap_result


