# STEP 5: Plot class analysis bar charts
# ===========================================================================

def plot_class_bar_chart(class_ap_result, class_order, chart_title, x_label, out_path):
    """
    This function creates a grouped bar chart showing mean AP@10 for each
    system broken down by class group.

    class_ap_result : result from compute_class_ap
    class_order     : ordered list of class values to show on x-axis
    chart_title     : title for the plot
    x_label         : label for x axis
    out_path        : where to save the image
    """
    # Get system names from result
    system_names = list(class_ap_result.keys())
    num_systems = len(system_names)
    num_classes = len(class_order)

    # We will place bars side by side for each class group
    bar_width = 0.8 / float(num_systems)

    fig, ax = plt.subplots(figsize=(12, 6))

    # x positions for the groups
    x_positions = []
    for i in range(num_classes):
        x_positions.append(float(i))

    # Drawing bars for each system
    for sys_idx in range(num_systems):
        sys_name = system_names[sys_idx]
        sys_data = class_ap_result[sys_name]

        # Collecting mean AP values in the correct class order
        map_values = []
        for cv in class_order:
            if cv in sys_data:
                map_values.append(sys_data[cv]["mean_ap"])
            else:
                map_values.append(0.0)

        # Calculate bar positions
        bar_positions = []
        for i in range(len(x_positions)):
            offset = (sys_idx - num_systems / 2.0 + 0.5) * bar_width
            bar_positions.append(x_positions[i] + offset)

        ax.bar(bar_positions, map_values, bar_width, label=sys_name)

    ax.set_xticks(x_positions)
    ax.set_xticklabels(class_order)
    ax.set_xlabel(x_label)
    ax.set_ylabel("Mean AP@10")
    ax.set_title(chart_title)
    ax.legend(loc='upper right', fontsize=7)
    ax.grid(axis='y', alpha=0.4)
    plt.tight_layout()
    plt.savefig(out_path, dpi=150)
    plt.close()
    print("  Saved chart:", out_path)


