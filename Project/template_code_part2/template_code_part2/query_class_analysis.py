# query_class_analysis.py
# ========================
# This script reads the already-computed outputs from part5.py and does
# a deeper class-level breakdown of the results. We need this for the report
# because the professor's schematic says: "for which CLASS did this happen."
#
# We classify queries by two different axes:
#   1) Query Length  : short (<=5 words), medium (6-10 words), long (>=11 words)
#   2) Qrel Density  : sparse (1-3 relevant docs), medium (4-9), dense (>=10)
#
# We also find universal failures (queries where every single method scores AP=0)
# and do a breakdown of PRF-vs-BM25 and LSA-vs-BM25 to explain marginal gaps.
#
# Inputs (all from output/ folder, generated by part5.py):
#   output/part5_full_per_query_ap.json   <- full per-query AP for all systems
#   output/part5_failure_analysis.json    <- existing failure data
#   cranfield/cran_queries.json           <- raw query text
#   cranfield/cran_qrels.json             <- relevance data for density
#
# Outputs saved to output/:
#   part5_query_length_class_analysis.json
#   part5_query_density_class_analysis.json
#   part5_length_class_chart.png
#   part5_density_class_chart.png
#   part5_universal_failures.json
#   part5_prf_vs_bm25_breakdown.json
#   part5_lsa_vs_bm25_breakdown.json
#   part5_failure_boundary_conditions.json

