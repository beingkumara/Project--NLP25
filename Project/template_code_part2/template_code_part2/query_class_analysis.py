# ===========================================================================

def save_json_file(data, path):
    """
    This function saves the given data as a JSON file at the given path.
    We use indent=4 so it is easy to read later.
    """
    f = open(path, 'w')
    json.dump(data, f, indent=4)
    f.close()
    print("  Saved:", path)


