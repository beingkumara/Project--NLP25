# STEP 3: Compute per-class average AP for each system
# ===========================================================================

def compute_class_ap(per_query_ap_data, query_ids_list, class_info_dict, class_key):
    """
    This function computes the average AP for each system broken down by class.
    For example, class_key = "length_group" gives us AP per (system, short/medium/long) pair.

    Parameters:
      per_query_ap_data : dict with "query_ids" list and system_name -> [ap values]
      query_ids_list    : ordered list of query IDs matching the AP lists
      class_info_dict   : {query_id -> {class_key: "short"/"medium"/etc, ...}}
      class_key         : the key to use for grouping ("length_group" or "density_group")

    Returns: {system_name -> {class_value -> {"count": N, "mean_ap": V}}}
    """
    # First let us find all the unique class values
    all_class_values = []
    for q_id in class_info_dict:
        class_val = class_info_dict[q_id][class_key]
        if class_val not in all_class_values:
            all_class_values.append(class_val)

    # Get the list of system names from the data
    system_names = []
    for key in per_query_ap_data.keys():
        if key != "query_ids":
            system_names.append(key)

    # For each system, for each class value, accumulate AP values
    result = {}

    for sys_idx in range(len(system_names)):
        sys_name = system_names[sys_idx]
        ap_list = per_query_ap_data[sys_name]

        # Initialize storage for each class
        class_ap_sums = {}
        class_counts = {}
        for cv in all_class_values:
            class_ap_sums[cv] = 0.0
            class_counts[cv] = 0

        # Go through all queries and accumulate
        for q_idx in range(len(query_ids_list)):
            q_id = query_ids_list[q_idx]
            ap_val = ap_list[q_idx]

            # Check if this query has class info
            if q_id in class_info_dict:
                class_val = class_info_dict[q_id][class_key]
                class_ap_sums[class_val] = class_ap_sums[class_val] + ap_val
                class_counts[class_val] = class_counts[class_val] + 1

        # Compute the mean AP for each class
        sys_result = {}
        for cv in all_class_values:
            if class_counts[cv] > 0:
                mean_ap = class_ap_sums[cv] / float(class_counts[cv])
            else:
                mean_ap = 0.0
            sys_result[cv] = {
                "count": class_counts[cv],
                "mean_ap": round(mean_ap, 4)
            }

        result[sys_name] = sys_result

    return result


