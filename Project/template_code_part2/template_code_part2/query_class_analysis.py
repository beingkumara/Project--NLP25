# STEP 1: Determine query length group for each query
# ===========================================================================

def get_query_length_groups(all_queries_list):
    """
    This function assigns each query to a length group based on word count.
    We count the raw word count (splitting on spaces) of the query text.

    Groups:
      short  : <= 5 words
      medium : 6 to 10 words
      long   : >= 11 words

    Returns a dictionary: {query_id -> {"length_words": N, "length_group": "..."}}
    """
    length_info = {}

    for i in range(len(all_queries_list)):
        q_entry = all_queries_list[i]
        q_id = int(q_entry["query number"])
        q_text = q_entry["query"]

        # Count words by splitting on whitespace
        words = q_text.strip().split()
        num_words = len(words)

        # Now deciding the group
        if num_words <= 5:
            group_name = "short"
        elif num_words <= 10:
            group_name = "medium"
        else:
            group_name = "long"

        length_info[q_id] = {
            "length_words": num_words,
            "length_group": group_name,
            "query_text": q_text
        }

    return length_info


# ===========================================================================
# STEP 2: Determine qrel density group for each query
# ===========================================================================

def get_qrel_density_groups(all_qrels_list):
    """
    This function counts how many relevant documents each query has in qrels.
    A document is relevant if its position is 1, 2, 3, or 4.

    Groups:
      sparse : 1 to 3 relevant documents
      medium : 4 to 9 relevant documents
      dense  : >= 10 relevant documents

    Returns a dictionary: {query_id -> {"relevant_count": N, "density_group": "..."}}
    """
    # First we count how many relevant docs each query has
    relevant_count_per_query = {}

    for i in range(len(all_qrels_list)):
        entry = all_qrels_list[i]
        q_id = int(entry["query_num"])
        pos = entry["position"]

        # Only count if position indicates relevance
        if pos == 1 or pos == 2 or pos == 3 or pos == 4:
            if q_id not in relevant_count_per_query:
                relevant_count_per_query[q_id] = 0
            relevant_count_per_query[q_id] = relevant_count_per_query[q_id] + 1

    # Now assign density group based on count
    density_info = {}

    for q_id in relevant_count_per_query:
        count = relevant_count_per_query[q_id]

        if count <= 3:
            group_name = "sparse"
        elif count <= 9:
            group_name = "medium"
        else:
            group_name = "dense"

        density_info[q_id] = {
            "relevant_count": count,
            "density_group": group_name
        }

    return density_info


